import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
let rpcCalls = [];
const supabase = { rpc: async (name, args) => { rpcCalls.push({ name, args }); return { data: { outcome: 'approved', status: 'PendingApproval' }, error: null }; } };
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('services/onCallBatchApproval.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports, require: () => ({ supabase }) });
const { approveOnCallBatch, approveOnCallQueueItem } = exports;
const item = id => ({ id, snapshot: {revision:1,grand_total:800}, summary:{complete:true}, reference: 'MP-' + id, employee: 'Fixture ' + id });
await approveOnCallQueueItem(item('a'));
assert.equal(rpcCalls[0].name, 'approve_oncall_queue_item');
assert.equal(rpcCalls[0].args.p_request_id, 'a');
assert.equal(rpcCalls[0].args.p_expected_snapshot.grand_total, 800);
const calls = [], progress = [];
const result = await approveOnCallBatch([item('a'), item('b'), item('a'), item('c'), item('d')], value => progress.push(value), async entry => {
  calls.push(entry.id);
  if (entry.id === 'b') return { outcome: 'skipped', reason: 'Revised.' };
  if (entry.id === 'c') throw new Error('Connection lost; decision unconfirmed.');
  return { outcome: 'approved', status: 'PendingApproval' };
});
assert.deepEqual(calls, ['a', 'b', 'c', 'd'], 'Only selected unique notices; continue after a failure without retrying.');
assert.equal(result.succeeded, 2); assert.equal(result.skipped, 1); assert.equal(result.failed, 1);
assert.equal(result.processed, 4); assert.equal(progress[0].processed, 1); assert.equal(progress[0].successIds.length, 1);
assert.match(result.skippedItems[0].reason, /MP-b.*Fixture b.*Revised/);
assert.match(result.failures[0].error, /MP-c.*Fixture c/);
const unknown = await approveOnCallBatch([item('x')], () => {}, async () => null);
assert.equal(unknown.failed, 1); assert.equal(unknown.succeeded, 0);
let attempted = false;
const missing = await approveOnCallBatch([{ ...item('x'), summary: {complete:false} }], () => {}, async () => { attempted = true; });
assert.equal(missing.failed, 1); assert.equal(attempted, false);
await assert.rejects(() => approveOnCallBatch([], () => {}), /Select at least one/);
console.log('PASS on-call batch: scoped unique selection, precise version guard, progress, partial results, no uncertain retries.');
