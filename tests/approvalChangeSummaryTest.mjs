import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const load = (path, deps={}) => {
  const exports={};
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(path,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports,require:name=>deps[name],Map,Set,Error});
  return exports;
};
const {getApprovalChangeSummary:summary}=load('utils/approvalChangeSummary.ts');
const p=(kind,data)=>({id:'test',kind,snapshot:'version',data});
const pan=summary(p('pan',{action:{changeOfStatus:true,salaryIncrease:true},particulars:{from:{employmentStatus:'Probationary',salary:{basic:20000,deminimis:1000,reimbursable:2000}},to:{employmentStatus:'Regular',salary:{basic:'25000',deminimis:1000,reimbursable:0,payBasis:'net_tax'}}}}));
assert.match(pan.title,/Status change.*Salary increase/);
assert.ok(pan.lines.some(l=>l.before==='Probationary'&&l.after==='Regular'));
assert.ok(pan.lines.some(l=>l.label==='Basic pay (+₱5,000)'&&l.after==='₱25,000'));
assert.ok(pan.lines.some(l=>l.label==='Reimbursable allowance (−₱2,000)'&&l.after==='₱0'));
assert.ok(pan.lines.some(l=>l.label==='Tax responsibility'&&l.after.includes('employer')));
const missing=summary(p('pan',{particulars:{from:{},to:{salary:{basic:1000}}}}));
assert.ok(missing.lines.some(l=>l.before==='Not recorded'&&l.after==='₱1,000'));
const req=summary(p('requisition',{headcount:3,employmentType:'Seasonal',seasonalMonths:5,salaryMin:20000,salaryMax:25000,locationType:'Onsite'}));
assert.equal(req.title,'3 hires · Seasonal · 5 months');
assert.equal(req.lines[1].value,'₱60,000–₱75,000');
assert.match(req.note,/benefits.*additional.*period is not specified/);
assert.equal(summary(p('requisition',{headcount:1,salaryMin:0,salaryMax:0})).lines[0].value,'Budget not recorded');
assert.equal(summary(p('requisition',{headcount:2,salaryMin:30000,salaryMax:20000})).lines[1].value,'Budget range needs review');
const component=(name,amount,frequency='Monthly',category='fixed_allowance')=>({name,amount,frequency,category});
const pay=summary(p('pay_package',{previous:{base_amount:500,rate_type:'Daily',components:[component('Food',1000),component('Old',200)]},proposed:{base_amount:600,rate_type:'Daily',components:[component('Food',2000),component('Receipt',45000,'Quarterly','reimbursable_allowance')]}}));
assert.deepEqual(JSON.parse(JSON.stringify(pay.lines[0])),{label:'Base pay',before:'₱500 / Daily',after:'₱600 / Daily'});
assert.ok(pay.lines.some(l=>l.label==='Base pay change'&&l.value==='+₱100 / Daily'));
assert.ok(pay.lines.some(l=>l.label==='Receipt'&&l.after==='₱45,000 / Quarterly · receipt required'));
assert.ok(pay.lines.some(l=>l.label==='Old'&&l.after==='Not included'));
assert.ok(!pay.lines.some(l=>/monthly.*cost/i.test(l.label)), 'Never present daily pay as a monthly company cost.');
const fresh=summary(p('pay_package',{proposed:{base_amount:600,rate_type:'Daily',components:[]}}));
assert.match(fresh.note,/No earlier approved/);
assert.equal(fresh.lines[0].before,undefined);

let reads=[];
const {approveChangeBatch,fetchApprovalChangePreviews}=load('services/changeApprovalBatch.ts',{'./supabaseClient':{supabase:{rpc:async(name,args)=>{reads.push({name,args});return {data:args.p_ids.map(id=>({id})),error:null};}}}});
assert.equal((await fetchApprovalChangePreviews('pan',Array.from({length:601},(_,i)=>String(i)))).length,601);
assert.deepEqual(reads.map(r=>r.args.p_ids.length),[250,250,101]);
const items=['pan','requisition','pay_package'].map((kind,i)=>({id:String(i),kind,snapshot:'v',reference:kind,employee:'Fixture'}));
let progress=[];
const result=await approveChangeBatch([...items,items[0]],r=>progress.push(r),async(item)=>{
 if(item.kind==='pan')return {outcome:'approved'};
 if(item.kind==='requisition')return {outcome:'skipped',reason:'Details changed'};
 throw new Error('Network interrupted');
});
assert.equal(result.succeeded,1);assert.equal(result.skipped,1);assert.equal(result.failed,1);assert.equal(result.processed,3);
assert.deepEqual(progress.map(r=>r.processed),[1,2,3]);
assert.equal(progress[0].failures.length,0,'Progress snapshots are immutable.');
console.log('Approval change summaries and batch processing passed.');
