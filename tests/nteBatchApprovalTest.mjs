import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
let rpcCalls = [];
const supabase = { rpc: async (name, args) => { rpcCalls.push({ name, args }); return { data: { outcome: 'approved', status: 'PendingApproval' }, error: null }; } };
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('services/nteBatchApproval.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports, require: () => ({ supabase }) });
const { approveNTEBatch, approveNTEQueueItem } = exports;
const item = id => ({ id, approvalId: 'approval-' + id, updatedAt: '2026-10-16T23:00:00.123456+00:00', reference: 'NTE-' + id, employee: 'Fixture ' + id });
await approveNTEQueueItem(item('a'));
assert.equal(rpcCalls[0].name, 'approve_nte_queue_item');
assert.equal(rpcCalls[0].args.p_approval_id, 'approval-a');
assert.equal(rpcCalls[0].args.p_expected_updated_at, item('a').updatedAt, 'Keep database timestamp precision.');
const calls = [], progress = [];
const result = await approveNTEBatch([item('a'), item('b'), item('a'), item('c'), item('d')], value => progress.push(value), async entry => {
  calls.push(entry.id);
  if (entry.id === 'b') return { outcome: 'skipped', reason: 'Revised.' };
  if (entry.id === 'c') throw new Error('Connection lost; decision unconfirmed.');
  return { outcome: 'approved', status: 'PendingApproval' };
});
assert.deepEqual(calls, ['a', 'b', 'c', 'd'], 'Only selected unique notices; continue after a failure without retrying.');
assert.equal(result.succeeded, 2); assert.equal(result.skipped, 1); assert.equal(result.failed, 1);
assert.equal(result.processed, 4); assert.equal(progress[0].processed, 1); assert.equal(progress[0].successIds.length, 1);
assert.match(result.skippedItems[0].reason, /NTE-b.*Fixture b.*Revised/);
assert.match(result.failures[0].error, /NTE-c.*Fixture c/);
const unknown = await approveNTEBatch([item('x')], () => {}, async () => null);
assert.equal(unknown.failed, 1); assert.equal(unknown.succeeded, 0);
let attempted = false;
const missing = await approveNTEBatch([{ ...item('x'), updatedAt: '' }], () => {}, async () => { attempted = true; });
assert.equal(missing.failed, 1); assert.equal(attempted, false);
await assert.rejects(() => approveNTEBatch([], () => {}), /Select at least one/);
console.log('PASS NTE batch: scoped unique selection, precise version guard, progress, partial results, no uncertain retries.');
